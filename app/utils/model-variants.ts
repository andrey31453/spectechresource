/** Запись версии по коду — для подписи над блоком. */
export function modelVariant(key: HomeModelVariant["key"]): HomeModelVariant {
  const found = HOME_MODEL_VARIANTS.find((variant) => variant.key === key);

  if (!found) throw new Error(`Неизвестная версия блока «Каталог моделей»: ${key}`);

  return found;
}
