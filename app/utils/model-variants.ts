/**
 * Версии блока «Каталог моделей» — витрина дизайн-вариантов на главной.
 *
 * Заказчик сравнивает вёрстку глазами, поэтому на странице одновременно живут
 * четыре версии одного блока подряд. Список ниже — единственный источник правды:
 * из него строится навигация сравнения и подпись над каждой версией, а якоря
 * `modeli-variant-*` совпадают с `id` секций на странице.
 *
 * В продакшн останется одна версия: лишние компоненты, этот список и подписи
 * удаляются вместе с выбранной разметкой (см. `docs/specs/home.md`).
 */

export interface HomeModelVariant {
  /** Короткий код: `A`, `B`, `C`, `D` — им помечены подпись и навигация. */
  key: "a" | "b" | "c" | "d";
  /** Якорь секции на странице (без `#`). */
  id: string;
  /** Название версии — то, что видит заказчик. */
  title: string;
  /** На что смотреть в этой версии: одна строка подписи. */
  note: string;
}

